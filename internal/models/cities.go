// API для автодополнения городов
func AutocompleteCities(w http.ResponseWriter, r *http.Request) {
	query := strings.ToLower(r.URL.Query().Get("q"))
	if query == "" {
		json.NewEncoder(w).Encode([]string{})
		return
	}

	matchesMap := make(map[string]bool)
	for _, city := range cities {
		if strings.Contains(strings.ToLower(city), query) {
			matchesMap[city] = true
			if len(matchesMap) >= 10 { // ограничиваем до 10 результатов
				break
			}
		}
	}

	var matches []string
	for city := range matchesMap {
		matches = append(matches, city)
	}
	sort.Strings(matches)

	w.Header().Set("Content-Type", "application/json")
	json.NewEncoder(w).Encode(matches)
}

// Валидация города
func validateCity(city string) bool {
	for _, c := range cities {
		if strings.EqualFold(c, city) {
			return true
		}
	}
	return false
}

